/**
 * Catalog tools. Category is folded into tags (single taxonomy: tags only).
 * `category` remains on the meta object for stable primary domain label.
 */
export const TOOLS: ToolMeta[] = TOOLS_RAW.map((t) => ({
  ...t,
  tags: normalizeTags([t.category, ...t.tags]),
  created: t.created ?? TOOL_DATES[t.id]?.created,
  updated: t.updated ?? TOOL_DATES[t.id]?.updated,
}))

/** All tags used on at least one tool (sorted). Catalog multi-filter: ?tags=a,b. */
export const ALL_TAGS = [...new Set(TOOLS.flatMap((t) => t.tags))].sort()

/** Primary domain tag for a tool (former category, always present after merge). */
export function primaryTag(tool: ToolMeta): string {
  return tool.category
}

export function getTool(id: string): ToolMeta | undefined {
  return TOOLS.find((t) => t.id === id)
}
