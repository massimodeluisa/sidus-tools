/**
 * Bundle mcp/http-handler.ts into a single api/mcp.js for Vercel.
 * Node ESM on Vercel cannot resolve extensionless ../mcp/create-server imports.
 */
import * as esbuild from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ['mcp/http-handler.ts'],
  outfile: 'api/mcp.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  logLevel: 'info',
  banner: {
    js: '/* Generated by scripts/bundle-mcp-api.mjs from mcp/http-handler.ts. Do not edit. */\n',
  },
})
